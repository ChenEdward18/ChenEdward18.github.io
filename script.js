const root = document.documentElement;
const header = document.querySelector('.site-header');
const menuToggle = document.querySelector('.menu-toggle');
const navPanel = document.querySelector('.nav-panel');
const languageToggle = document.querySelector('.language-toggle');
const themeToggle = document.querySelector('.theme-toggle');
const themeIcon = document.querySelector('.theme-icon');
const backToTop = document.querySelector('.back-to-top');
const toast = document.querySelector('.toast');
const resumeButton = document.querySelector('.resume-button');
const resumeNote = document.querySelector('.resume-note');
let currentLanguage = localStorage.getItem('wyc-language') || 'zh';
let toastTimer;

function applyLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];
  root.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]').content = dictionary.pageDescription;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) element.setAttribute('aria-label', dictionary[key]);
  });
  languageToggle.textContent = language === 'zh' ? 'EN' : '中';
  languageToggle.setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换为中文');
  localStorage.setItem('wyc-language', language);
  updateThemeControl();
}

function preferredTheme() {
  const storedTheme = localStorage.getItem('wyc-theme');
  if (storedTheme) return storedTheme;
  return window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
}

function updateThemeControl() {
  const isDark = root.dataset.theme === 'dark';
  themeIcon.textContent = isDark ? '☀' : '☾';
  const label = currentLanguage === 'zh'
    ? (isDark ? '切换为浅色主题' : '切换为深色主题')
    : (isDark ? 'Switch to light theme' : 'Switch to dark theme');
  themeToggle.setAttribute('aria-label', label);
}

function closeMenu() {
  navPanel.classList.remove('open');
  menuToggle.setAttribute('aria-expanded', 'false');
  document.body.classList.remove('menu-open');
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add('visible');
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove('visible'), 2200);
}

languageToggle.addEventListener('click', () => applyLanguage(currentLanguage === 'zh' ? 'en' : 'zh'));
themeToggle.addEventListener('click', () => {
  const nextTheme = root.dataset.theme === 'dark' ? 'light' : 'dark';
  root.dataset.theme = nextTheme;
  localStorage.setItem('wyc-theme', nextTheme);
  updateThemeControl();
});
menuToggle.addEventListener('click', () => {
  const willOpen = menuToggle.getAttribute('aria-expanded') !== 'true';
  navPanel.classList.toggle('open', willOpen);
  menuToggle.setAttribute('aria-expanded', String(willOpen));
  document.body.classList.toggle('menu-open', willOpen);
});
document.querySelectorAll('.nav-links a').forEach((link) => link.addEventListener('click', closeMenu));
document.addEventListener('keydown', (event) => { if (event.key === 'Escape') closeMenu(); });

resumeButton.addEventListener('click', () => {
  resumeNote.classList.toggle('visible');
  if (resumeNote.classList.contains('visible')) showToast(translations[currentLanguage].resumeNote);
});

document.querySelectorAll('.copy-button').forEach((button) => {
  button.addEventListener('click', async () => {
    const value = button.dataset.copy;
    try {
      await navigator.clipboard.writeText(value);
      showToast(`${translations[currentLanguage].copied}${value}`);
    } catch {
      showToast(translations[currentLanguage].copyFailed);
    }
  });
});

backToTop.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });
document.querySelectorAll('.reveal').forEach((element) => revealObserver.observe(element));

const sections = [...document.querySelectorAll('main section[id]')];
const navLinks = [...document.querySelectorAll('.nav-links a')];
const updateScrollState = () => {
  header.classList.toggle('scrolled', window.scrollY > 12);
  backToTop.classList.toggle('visible', window.scrollY > 600);
  const position = window.scrollY + 150;
  let currentSection = 'home';
  sections.forEach((section) => { if (position >= section.offsetTop) currentSection = section.id; });
  navLinks.forEach((link) => link.classList.toggle('active', link.getAttribute('href') === `#${currentSection}`));
};
window.addEventListener('scroll', updateScrollState, { passive: true });
window.addEventListener('resize', () => { if (window.innerWidth > 900) closeMenu(); });

root.dataset.theme = preferredTheme();
document.querySelector('#current-year').textContent = new Date().getFullYear();
applyLanguage(currentLanguage);
updateScrollState();
